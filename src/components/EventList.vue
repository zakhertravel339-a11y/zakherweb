<script setup>
import { ref, onMounted, onBeforeUnmount } from "vue";

let lightbox;
let lightboxImg;
let caption;

let images = [];
let currentIndex = 0;

function openImage(index) {
  const img = images[index];

  lightboxImg.src = img.src;
  lightboxImg.alt = img.alt || "";
  caption.textContent = img.alt || "";

  currentIndex = index;

  lightbox.classList.add("is-open");
  document.body.style.overflow = "hidden";
}

function closeImage() {
  lightbox.classList.remove("is-open");
  document.body.style.overflow = "";
}

function nextImage() {
  currentIndex = (currentIndex + 1) % images.length;
  openImage(currentIndex);
}

function prevImage() {
  currentIndex = (currentIndex - 1 + images.length) % images.length;
  openImage(currentIndex);
}

function onKeydown(e) {
  if (!lightbox.classList.contains("is-open")) return;

  if (e.key === "Escape") closeImage();
  if (e.key === "ArrowRight") nextImage();
  if (e.key === "ArrowLeft") prevImage();
}

onMounted(() => {
  lightbox = document.getElementById("lightbox");
  lightboxImg = document.getElementById("lightboxImg");
  caption = document.getElementById("lightboxCaption");

  images = Array.from(document.querySelectorAll(".gallery__item img"));

  
  images.forEach((img, index) => {
    img.addEventListener("click", () => openImage(index));
  });



  
  lightbox.querySelector(".lightbox__backdrop")
      .addEventListener("click", closeImage);

  
  document.querySelector("[data-next]").addEventListener("click", nextImage);
  document.querySelector("[data-prev]").addEventListener("click", prevImage);

  
  window.addEventListener("keydown", onKeydown);
});

onBeforeUnmount(() => {
  window.removeEventListener("keydown", onKeydown);
  document.body.style.overflow = "";
});
</script>
